CREATE OR REPLACE EDITIONABLE FUNCTION  "SPELL_OUT" (a_number NUMBER)
   RETURN CHAR
IS
   TYPE numtab IS TABLE OF VARCHAR2 (50)              -- single column pl/sql
      INDEX BY BINARY_INTEGER;               -- table declaration and indexed
   number_chart   numtab;                  -- table type variable declaration
   crore          NUMBER;                       -- other variable declaration
   lakh           NUMBER;
   thou           NUMBER;
   hund           NUMBER;
   doubl          NUMBER;
   sing           NUMBER;
   deci           NUMBER;
   text           VARCHAR2 (1000);
