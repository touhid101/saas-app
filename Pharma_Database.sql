                                 MAX (STRIP_SALES_PRICE_SPC) STRIP_SALES_PRICE_SPC,
                                 MAX (STRIP_SALES_PRICE_SPC_RET) STRIP_SALES_PRICE_SPC_RET,
                                 MAX (PCS_SALES_PRICE)      PCS_SALES_PRICE
                            FROM (SELECT /*+ NO_MERGE(PTM,PTD) ORDERED */ PTM.PID_BRANCH,
                                         AB.BRANCH_NAME,
                                         PTD.PID_PRODUCT,
                                         PRI.PID_COMPANY,
                                         PC.COMPANY_NAME,
                                         PTM.TRANSACTION_TYPE,
                                         PRI.PRODUCT_NAME,
                                         PB.BOX_SIZE_TITLE,
                                         PU.UNIT_NAME,
                                         PRI.SKU,
                                         PRI.ALERT_QTY,
                                         CASE
                                             WHEN PTM.PURCHASE_TYPE = 'MRP'
                                             THEN
                                                 PRI.MRP_PRICE
                                             WHEN PTM.PURCHASE_TYPE = 'MNP'
                                             THEN
                                                 PRI.BUY_PRICE
                                         END
                                             PURCHASE_PRICE,
                                         PRI.MRP_PRICE,
                                         NVL (PB.NO_OF_LEAF, 0)
                                             NO_OF_LEAF,
                                           NVL (PB.NO_OF_LEAF, 0)
                                         * NVL (PL.NO_OF_PCS, 0)
                                             AS NO_OF_PCS,
                                         TRUNC (PTD.EXPIRY_DATE)
                                             AS EXPIRY_DATE,
                                         TRUNC (PTM.TRANSACTION_DATE)
                                             TRANSACTION_DATE,
                                         CASE
                                             WHEN TRANSACTION_TYPE = 'SL'
                                             THEN
                                                 PTD.QUANTITY
                                         END
                                             SALES_QTY,
                                         CASE
                                             WHEN TRANSACTION_TYPE = 'SR'
                                             THEN
                                                 PTD.QUANTITY
                                         END
                                             SALES_RETURN_QTY,
                                         CASE
                                             WHEN TRANSACTION_TYPE = 'PU'
                                             THEN
                                                 PTD.QUANTITY
                                         END
                                             PURCHASE_QTY,
                                         CASE
                                             WHEN TRANSACTION_TYPE = 'PR'
                                             THEN
                                                 PTD.QUANTITY
                                         END
                                             PUR_RETURN_QTY,
                                         CASE
                                             WHEN TRANSACTION_TYPE IN ('SL')
                                             THEN
                                                 -PTD.QUANTITY
                                             WHEN TRANSACTION_TYPE IN ('PR')
                                             THEN
                                                 -(  PTD.QUANTITY
                                                   * NVL (PB.NO_OF_LEAF, 0)
                                                   * NVL (PL.NO_OF_PCS, 0))
                                             WHEN TRANSACTION_TYPE IN ('PU')
                                             THEN
                                                 (  PTD.QUANTITY
                                                  * NVL (PB.NO_OF_LEAF, 0)
                                                  * NVL (PL.NO_OF_PCS, 0))
                                             WHEN TRANSACTION_TYPE IN ('SR')
                                             THEN
                                                 PTD.QUANTITY
                                         END
                                             PRODUCT_QTY,
                                         CASE
                                             WHEN TRANSACTION_TYPE IN ('PU')
                                             THEN
                                                 ROUND (
                                                       (  NVL (PTD.TOTAL_PRICE, 0)
                                                        - NVL (
                                                              ROUND (
                                                                  (  (  NVL (
                                                                            PTD.TOTAL_PRICE,
                                                                            0)
                                                                      * NVL (
                                                                            PTM.INVOICE_DIS_PCT,
                                                                            0))
                                                                   / 100),
                                                                  2),
                                                              0))
                                                     / (NVL (PTD.QUANTITY, 0)),
                                                     2)
                                         END
                                             ACTUAL_PURCHASE,
                                             NVL (PRI.MRP_PRICE, 0)
                                           / (NULLIF (
                                                    NVL (PB.NO_OF_LEAF, 0)
                                                  * NVL (PL.NO_OF_PCS, 0),
                                                  0))
                                         - (  (  (  NVL (PRI.MRP_PRICE, 0)
                                                  / (NULLIF (
                                                           NVL (PB.NO_OF_LEAF, 0)
                                                         * NVL (PL.NO_OF_PCS, 0),
                                                         0)))
                                               * NVL (PRI.SALES_PER, 0))
                                            / 100)
                                             SALES_PRICE,
                                             NVL (PRI.MRP_PRICE, 0)
                                           / (NULLIF (
                                                    NVL (PB.NO_OF_LEAF, 0)
                                                  * NVL (PL.NO_OF_PCS, 0),
                                                  0))
                                         - (  (  (  NVL (PRI.MRP_PRICE, 0)
                                                  / (NULLIF (
                                                           NVL (PB.NO_OF_LEAF, 0)
                                                         * NVL (PL.NO_OF_PCS, 0),
                                                         0)))
                                               * NVL (PRI.SALES_PER_SPC, 0))
                                            / 100)
                                             SALES_PRICE_SPC,
                                             NVL (PRI.MRP_PRICE, 0)
                                           / (NULLIF (
                                                    NVL (PB.NO_OF_LEAF, 0)
                                                  * NVL (PL.NO_OF_PCS, 0),
                                                  0))
                                         - (  (  (  NVL (PRI.MRP_PRICE, 0)
                                                  / (NULLIF (
                                                           NVL (PB.NO_OF_LEAF, 0)
                                                         * NVL (PL.NO_OF_PCS, 0),
                                                         0)))
                                               * NVL (PRI.SALES_PER_LEAF, 0))
                                            / 100)
                                             STRIP_SALES_PRICE,
                                             NVL (PRI.MRP_PRICE, 0)
                                           / (NULLIF (
                                                    NVL (PB.NO_OF_LEAF, 0)
                                                  * NVL (PL.NO_OF_PCS, 0),
                                                  0))
                                         - (  (  (  NVL (PRI.MRP_PRICE, 0)
                                                  / (NULLIF (
                                                           NVL (PB.NO_OF_LEAF, 0)
                                                         * NVL (PL.NO_OF_PCS, 0),
                                                         0)))
                                               * NVL (PRI.SALES_PER_SPC_LEAF, 0))
                                            / 100)
                                             STRIP_SALES_PRICE_SPC,
                                             NVL (PRI.MRP_PRICE, 0)
                                           / (NULLIF (
                                                    NVL (PB.NO_OF_LEAF, 0)
                                                  * NVL (PL.NO_OF_PCS, 0),
                                                  0))
                                         - (  (  (  NVL (PRI.MRP_PRICE, 0)
                                                  / (NULLIF (
                                                           NVL (PB.NO_OF_LEAF, 0)
                                                         * NVL (PL.NO_OF_PCS, 0),
                                                         0)))
                                               * NVL (PRI.SALES_PER_SPC_RET, 0))
                                            / 100)
                                             STRIP_SALES_PRICE_SPC_RET,
                                             NVL (PRI.MRP_PRICE, 0)
                                           / (NULLIF (
                                                    NVL (PB.NO_OF_LEAF, 0)
                                                  * NVL (PL.NO_OF_PCS, 0),
                                                  0))
                                         - (  (  (  NVL (PRI.MRP_PRICE, 0)
                                                  / (NULLIF (
                                                           NVL (PB.NO_OF_LEAF, 0)
                                                         * NVL (PL.NO_OF_PCS, 0),
                                                         0)))
                                               * NVL (PRI.SALES_PER_PCS, 0))
                                            / 100)
                                             PCS_SALES_PRICE,
                                         CASE
                                             WHEN TRANSACTION_TYPE IN ('PU')
                                             THEN
                                                 ROUND (
                                                     (  NVL (PTD.TOTAL_PRICE, 0)
                                                      - NVL (
                                                            ROUND (
                                                                (  (  NVL (
                                                                          PTD.TOTAL_PRICE,
                                                                          0)
                                                                    * NVL (
                                                                          PTM.INVOICE_DIS_PCT,
                                                                          0))
                                                                 / 100),
                                                                2),
                                                            0)),
                                                     2)
                                         END
                                             TOTAL_PRICE,
                                         PTM.INVOICE_DIS_PCT
                                    FROM POS_TRANSACTION_MST PTM,
                                         POS_TRANSACTION_DTL PTD,
                                         POS_PRODUCT_INFO PRI,
                                         POS_BOX_INFO   PB,
                                         POS_LEAF_INFO  PL,
                                         POS_PRODUCT_UNIT PU,
                                         POS_COMPANY_INFO PC,
                                         ALL_BRANCH     AB
                                   WHERE     PTM.PID_TRAN_MST = PTD.PID_TRAN_MST
                                         AND PTD.PID_PRODUCT = PRI.PID_PRODUCT(+)
                                         AND PRI.PID_BOX = PB.PID_BOX(+)
                                         AND PB.PID_LEAF = PL.PID_LEAF(+)
                                         AND PRI.PID_UNIT = PU.PID_UNIT(+)
                                         AND PRI.PID_COMPANY = PC.PID_COMPANY(+)
                                         AND PTM.PID_BRANCH = AB.PID_BRANCH(+) 
                                         AND PTM.MERGE_PID_TRAN_MST IS NULL--AND PTM.STATUS = 'Y'
                                                                              --AND PRI.PID_PRODUCT=1242
                                                                              )
                        GROUP BY PID_BRANCH,
                                 BRANCH_NAME,
                                 PID_PRODUCT,
                                 PID_COMPANY,
                                 COMPANY_NAME,
                                 TRANSACTION_TYPE,
                                 PRODUCT_NAME,
                                 BOX_SIZE_TITLE,
                                 UNIT_NAME,
                                 SKU,
                                 ALERT_QTY,
                                 NO_OF_LEAF,
                                 NO_OF_PCS,
                                 EXPIRY_DATE) M,
                       (  SELECT /*+ first_row(10) */ PID_PRODUCT, EXPIRY_DATE, COUNT (*) TOT
                            FROM (SELECT /*+ full(A) */ UNIQUE
                                         PID_PRODUCT,
                                         TRUNC (B.EXPIRY_DATE)     EXPIRY_DATE
                                    FROM POS_TRANSACTION_MST A,
                                         POS_TRANSACTION_DTL B
                                   WHERE     A.PID_TRAN_MST = B.PID_TRAN_MST
                                         AND A.TRANSACTION_TYPE = 'PU' --AND B.PID_PRODUCT=1242
                                                                      )
                        GROUP BY PID_PRODUCT, EXPIRY_DATE) CTN
                 WHERE     M.PID_PRODUCT = CTN.PID_PRODUCT(+)
                       AND TRUNC (M.EXPIRY_DATE) = CTN.EXPIRY_DATE(+)
              GROUP BY PID_BRANCH,
                       BRANCH_NAME,
                       PID_COMPANY,
                       COMPANY_NAME,
                       M.PID_PRODUCT,
                       --TRANSACTION_TYPE,
                       PRODUCT_NAME,
                       M.EXPIRY_DATE,
                       BOX_SIZE_TITLE,
                       UNIT_NAME,
                       SKU,
                       ALERT_QTY,
                       MRP_PRICE,
                       NO_OF_PCS,
                       NO_OF_LEAF,
                       SALES_PRICE,
                       SALES_PRICE_SPC,
                       STRIP_SALES_PRICE,
                       STRIP_SALES_PRICE_SPC,
                       STRIP_SALES_PRICE_SPC_RET,
                       PCS_SALES_PRICE) A
    GROUP BY PID_BRANCH,
             BRANCH_NAME,
             PID_COMPANY,
             COMPANY_NAME,
             PID_PRODUCT,
             PRODUCT_NAME,
             EXPIRY_DATE,
             BOX_SIZE,
             NO_OF_PCS,
             UNIT_NAME,
             SKU,
