CREATE OR REPLACE EDITIONABLE PROCEDURE  "PROC_EXPIRY_WISE_SALES_QTY_DIS" 
(
pPID_PRODUCT NUMBER,
pQTY NUMBER,
pPID_TRAN_MST NUMBER,
pSALES_UNIT VARCHAR2

)
IS
vQTY NUMBER:=pQTY;
vBAL NUMBER:=0;
cursor c is  SELECT PID_PRODUCT, TO_DATE(EXPIRY_DATE,'DD/MM/RRRR') EXPIRY_DATE, STOCK_QTY,ACTUAL_PURCHASE as MRP_PRICE,
CASE WHEN pSALES_UNIT='BOX' THEN SALES_PRICE 
     WHEN pSALES_UNIT='STRIP' THEN STRIP_SALES_PRICE 
     WHEN pSALES_UNIT='PCS' THEN PCS_SALES_PRICE 
     END SALES_PRICE
                FROM VW_PRODUCT_STOCK  
                WHERE STOCK_QTY > 0 AND PID_PRODUCT=pPID_PRODUCT
                ORDER BY EXPIRY_DATE;
BEGIN


     for x in c loop   

            if vQTY>=x.STOCK_QTY THEN
               vBAL:=vQTY-x.STOCK_QTY;
            elsif (vQTY>0 and vQTY<x.STOCK_QTY) THEN
             vBAL:=vQTY;
            end if;

        if (vQTY>0 and vBAL>=0) then

             if vQTY>=x.STOCK_QTY THEN
        insert into POS_TRANSACTION_DTL (
                      PID_TRAN_MST
                     ,EXPIRY_DATE
                    , PID_PRODUCT
                    , QUANTITY
                    , MRP_PRICE
                    , SALES_PRICE
                    , TOTAL_PRICE
                    , SALES_TYPE
                )values(
                      pPID_TRAN_MST
                    , x.EXPIRY_DATE
                    , pPID_PRODUCT
                    , x.STOCK_QTY
                    , x.MRP_PRICE
                    , x.SALES_PRICE
                    , x.STOCK_QTY*x.SALES_PRICE
                    , pSALES_UNIT
                );
          elsif (vQTY>0 and vQTY<x.STOCK_QTY) THEN       
               insert into POS_TRANSACTION_DTL (
                      PID_TRAN_MST
                     ,EXPIRY_DATE
                    , PID_PRODUCT
                    , QUANTITY
                    , MRP_PRICE
                    , SALES_PRICE
                    , TOTAL_PRICE
                    , SALES_TYPE
                )values(
                      pPID_TRAN_MST
                    , x.EXPIRY_DATE
                    , pPID_PRODUCT
                    , vQTY
                    , x.MRP_PRICE
                    , x.SALES_PRICE
                    , vQTY*x.SALES_PRICE
                    , pSALES_UNIT
                ); 
                
         end if;

        commit;
        end if;
        if vQTY>=x.STOCK_QTY THEN
               vQTY:=vBAL;
            elsif (vQTY>0 and vQTY<x.STOCK_QTY) THEN
             vQTY:=0;
            end if;
       end loop;
END;
