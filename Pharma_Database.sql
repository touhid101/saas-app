CREATE OR REPLACE EDITIONABLE FUNCTION  "FN_NUMBER_TO_WORD" (a_number NUMBER) RETURN VARCHAR2 IS
    TYPE numtab IS TABLE OF VARCHAR2(30) INDEX BY BINARY_INTEGER;
    number_chart numtab;
    
    crore NUMBER;
    lakh NUMBER;
    thou NUMBER;
    hund NUMBER;
    tens NUMBER;
    ones NUMBER;
    deci NUMBER;
    
    text VARCHAR2(500);
BEGIN
    -- The Number Words Mapping
    number_chart(1) := 'One';
    number_chart(2) := 'Two';
    number_chart(3) := 'Three';
    number_chart(4) := 'Four';
    number_chart(5) := 'Five';
    number_chart(6) := 'Six';
    number_chart(7) := 'Seven';
    number_chart(8) := 'Eight';
    number_chart(9) := 'Nine';
    number_chart(10) := 'Ten';
    number_chart(11) := 'Eleven';
    number_chart(12) := 'Twelve';
    number_chart(13) := 'Thirteen';
    number_chart(14) := 'Fourteen';
    number_chart(15) := 'Fifteen';
    number_chart(16) := 'Sixteen';
    number_chart(17) := 'Seventeen';
    number_chart(18) := 'Eighteen';
    number_chart(19) := 'Nineteen';
    number_chart(20) := 'Twenty';
    number_chart(30) := 'Thirty';
    number_chart(40) := 'Forty';
    number_chart(50) := 'Fifty';
    number_chart(60) := 'Sixty';
    number_chart(70) := 'Seventy';
    number_chart(80) := 'Eighty';
    number_chart(90) := 'Ninety';

    -- Extracting Digits
    crore := FLOOR(a_number / 10000000);
    lakh := FLOOR(MOD(a_number, 10000000) / 100000);
    thou := FLOOR(MOD(a_number, 100000) / 1000);
    hund := FLOOR(MOD(a_number, 1000) / 100);
    tens := FLOOR(MOD(a_number, 100) / 10) * 10; -- Extracting tens
    ones := FLOOR(MOD(a_number, 10)); -- Extracting ones
    deci := ROUND(MOD(a_number, 1) * 100); -- Extracting Paisa

    text := '';

    -- Crore
    IF crore > 0 THEN
        text := text || number_chart(crore) || ' Crore ';
    END IF;

    -- Lakh
    IF lakh <> 0
   THEN                                                 -- Translating in word
      IF (lakh <= 20) OR (lakh MOD 10 = 0)
      THEN                                                    -- other values
         text := text || number_chart (lakh) || ' Lakh ';
      ELSE
         text :=
               text
            || number_chart (TRUNC (lakh, -1))
            || '-'
            || number_chart (TRUNC (lakh, 0) - TRUNC (lakh, -1))
            || ' Lakh ';
      END IF;
   END IF;
   IF thou <> 0
   THEN
      IF (thou <= 20) OR (thou MOD 10 = 0)
      THEN
         text := text || number_chart (thou) || ' Thousand ';
      ELSE
         text :=
               text
            || number_chart (TRUNC (thou, -1))
            || '-'
            || number_chart (TRUNC (thou, 0) - TRUNC (thou, -1))
            || ' Thousand ';
      END IF;
   END IF;
   IF hund <> 0
   THEN
      IF (hund <= 20) OR (hund MOD 10 = 0)
      THEN
         text := text || number_chart (hund) || ' Hundred ';
      ELSE
         text :=
               text
            || number_chart (TRUNC (hund, -1))
            || '-'
            || number_chart (TRUNC (hund, 0) - TRUNC (hund, -1))
            || ' Hundred ';
      END IF;
   END IF;
--   IF doubl <> 0
--   THEN
