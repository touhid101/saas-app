CREATE OR REPLACE EDITIONABLE PROCEDURE  "PROC_AUTO_CLOSE_NOT_SUBIMITTED" 
AS

    cursor C IS
    select PT.PID_TRAN_MST
    from POS_TRANSACTION_MST PT,POS_TRANSACTION_DTL PD
    where PT.PID_TRAN_MST = PD.PID_TRAN_MST 
    AND PT.STATUS IS NULL AND PT.FROM_SOURCE='APPS' AND PT.TRANSACTION_TYPE='SL'
    HAVING to_date(to_char(MAX(PD.INSERTED_DATE),'DD-MM-RRRR HH24:MI'),'DD-MM-RRRR HH24:MI') + 1440/1440 <= to_date(to_char(sysdate,'DD-MM-RRRR HH24:MI'),'DD-MM-RRRR HH24:MI')
    --and PT.PID_TRAN_MST=172607
    GROUP BY PT.PID_TRAN_MST;
begin
    for i in C loop
        begin
        DELETE from POS_TRANSACTION_DTL WHERE PID_TRAN_MST = i.PID_TRAN_MST;
        DELETE from POS_TRANSACTION_MST WHERE PID_TRAN_MST = i.PID_TRAN_MST;
       
        exception when others then null;
        end;
    commit;     
    end loop;
exception when others then raise;
end;
