CREATE OR REPLACE EDITIONABLE FUNCTION  "FN_INVOICE_NO_GEN" (pTRANSACTION_TYPE  VARCHAR2) return varchar2
                        is
                        vYearMonth   VARCHAR2(6); -- Current Year-Month (RRMM)
                        vLastYearMonth VARCHAR2(6); -- Last Year-Month from Tracker
                        vINVOICE_NO    VARCHAR2(15); -- Final Generated Lot
                        pragma autonomous_transaction;
                    BEGIN
                        /** New finish id creation**/
                        if vINVOICE_NO is null then
                        -- Get current year and month
                        vYearMonth := TO_CHAR(SYSDATE, 'RRMM');

                        -- Fetch the last year-month from the tracker
                        SELECT LAST_YEAR_MONTH
                        INTO vLastYearMonth
                        FROM SEQUENCE_TRACKER
                        WHERE SEQ_NAME = 'SEQ_INVOICE_NO';

                        -- Check if year-month has changed
                        IF vYearMonth != vLastYearMonth THEN
                            -- Reset the sequence by dropping and recreating it
                            --EXECUTE IMMEDIATE 'DROP SEQUENCE SEQ_INVOICE_NO';
                            --EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_INVOICE_NO START WITH 1 INCREMENT BY 1 NOCACHE';
                            
                            EXECUTE IMMEDIATE 'ALTER SEQUENCE SEQ_INVOICE_NO RESTART START WITH 1';
                            


                            -- Update the tracker table with the new year-month
                            UPDATE SEQUENCE_TRACKER
                            SET LAST_YEAR_MONTH = vYearMonth
                            WHERE SEQ_NAME = 'SEQ_INVOICE_NO';

                            COMMIT;
                        END IF;

                        -- Generate the APEX_LOT using the sequence
                        vINVOICE_NO := pTRANSACTION_TYPE||vYearMonth|| LPAD(SEQ_INVOICE_NO.NEXTVAL, 5, '0');
                        END IF;
                        RETURN vINVOICE_NO;

                    EXCEPTION
                        WHEN OTHERS THEN
                            -- Handle errors
                            RAISE;
                    END;
/

