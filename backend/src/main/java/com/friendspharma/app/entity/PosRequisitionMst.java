package com.friendspharma.app.entity;

import com.friendspharma.app.entity.base.BaseEntity;
import jakarta.persistence.*;
import lombok.*;

import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

/**
 * Purchase-requisition master.
 * Workflow: DRAFT → SUBMITTED → PENDING_APPROVAL → APPROVED → CONVERTED (→ Purchase Order)
 * AI-sourced requisitions arrive as DRAFT and are shown on the Requisition page for qty editing
 * before submission.
 */
@Entity
@Table(name = "POS_REQUISITION_MST",
        indexes = {
            @Index(name = "IDX_REQ_ORG",    columnList = "PID_ORG"),
            @Index(name = "IDX_REQ_STAGE",  columnList = "STAGE"),
            @Index(name = "IDX_REQ_DATE",   columnList = "REQ_DATE")
        })
@Getter @Setter @NoArgsConstructor @AllArgsConstructor @Builder
public class PosRequisitionMst extends BaseEntity {

    @Id
    @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "SQ_REQ_MST")
    @SequenceGenerator(name = "SQ_REQ_MST", sequenceName = "SQ_REQ_MST", allocationSize = 1)
    @Column(name = "PID_REQUISITION")
    private Long pidRequisition;

    @Column(name = "REQUISITION_NO", length = 30, unique = true)
    private String requisitionNo;

    @Column(name = "PID_ORG", nullable = false)
    private Long pidOrg;

    @Column(name = "PID_BRANCH", nullable = false)
    private Long pidBranch;

    /**
     * Who the requisition is going to.
     *
     * <p>Nullable on purpose. A buyer working from the reorder list may raise
     * one covering several manufacturers and split it later; a buyer working
     * from a supplier raises one that is entirely that supplier's. When it is
     * set, every line must be a product of that supplier's manufacturer, and
     * the service refuses the ones that are not.
     */
    @Column(name = "PID_SUPPLIER")
    private Long pidSupplier;

    @Column(name = "REQ_DATE", nullable = false)
    private LocalDate reqDate;

    /**
     * DRAFT | SUBMITTED | PENDING_APPROVAL | APPROVED | CONVERTED | REJECTED | CANCELLED
     */
    @Column(name = "STAGE", nullable = false, length = 30)
    @Builder.Default
    private String stage = "DRAFT";

    /**
     * MANUAL – created by a user
     * AI      – generated by the AI recommendation engine
     */
    @Column(name = "SOURCE", nullable = false, length = 10)
    @Builder.Default
    private String source = "MANUAL";

    /** FK → AclUser — the user who created / submitted */
    @Column(name = "PID_CREATED_BY")
    private Long pidCreatedBy;

    /** FK → AclUser — the approver */
    @Column(name = "PID_APPROVED_BY")
    private Long pidApprovedBy;

    @Column(name = "APPROVED_AT")
    private java.time.LocalDateTime approvedAt;

    @Column(name = "REMARKS", length = 500)
    private String remarks;

    @Column(name = "REJECTION_REASON", length = 500)
    private String rejectionReason;

    /** Set when converted to a purchase order */
    @Column(name = "PID_PURCHASE_ORDER")
    private Long pidPurchaseOrder;

    @OneToMany(mappedBy = "requisition", cascade = CascadeType.ALL, orphanRemoval = true)
    @Builder.Default
    private List<PosRequisitionDtl> details = new ArrayList<>();
}
