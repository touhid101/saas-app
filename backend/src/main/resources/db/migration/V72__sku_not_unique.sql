/* ─────────────────────────────────────────────────────────────────────────────
   SKU stops being unique.

   A SKU in this system is a shelf or supplier reference typed by whoever enters
   the product. It is optional — 75 of the 120 products carry none, having
   arrived through the bulk importer or the catalogue copy, neither of which ever
   set one — and the business does not treat it as an identity: two products may
   legitimately carry the same code.

   The guard was therefore refusing entries the business considers valid, and
   refusing them at the point of a new product, which is the worst place to stop
   somebody. Dropping the index is what actually removes the rule: the service
   check alone was only half of it, and removing that half would have turned a
   clear "SKU already exists" into a raw constraint violation.

   What still identifies a product:

     PRODUCT_CODE   generated by the server, supplied by no client, unique.
     BARCODE        still unique per branch, still the primary scan key.

   Nothing about existing rows changes. The index only ever forbade new
   duplicates; the rows already stored satisfied it and go on satisfying nothing.
   ───────────────────────────────────────────────────────────────────────────── */

DROP INDEX IF EXISTS pharma.uq_product_branch_sku;

/* The older organisation-wide index, if this database still carries it. Named
   in the repository comments as UX_PRODUCT_SKU_ORG; harmless when absent. */
DROP INDEX IF EXISTS pharma.ux_product_sku_org;

/* A non-unique index in its place. Lookup by SKU is still on the read path —
   the POS scanner falls back to it and the bulk importer matches on it — and
   without an index those become sequential scans of the product table. */
CREATE INDEX IF NOT EXISTS ix_product_sku
    ON pharma.pos_product_info (COALESCE(pid_branch, 0), upper(sku))
 WHERE sku IS NOT NULL AND sku <> '';

/* What remains unique on this table, for the record. */
SELECT indexname, indexdef
  FROM pg_indexes
 WHERE schemaname = 'pharma'
   AND tablename  = 'pos_product_info'
   AND indexdef ILIKE '%UNIQUE%'
 ORDER BY indexname;
