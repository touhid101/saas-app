DECLARE
    PROCEDURE grant_all(p_group NUMBER, p_module NUMBER) IS
    BEGIN
        INSERT INTO POS_PERMISSIONS
            (PID_PERMISSION, PID_GROUP, PID_MODULE,
             CAN_VIEW, CAN_CREATE, CAN_EDIT, CAN_DELETE,
             CAN_APPROVE, CAN_PRINT, CAN_EXPORT, CAN_FINALIZE, CAN_CANCEL,
             INSERTED_DATE, INSERTED_BY)
        VALUES (
            SEQ_POS_PERMISSIONS.NEXTVAL, p_group, p_module,
            'Y','Y','Y','Y','Y','Y','Y','Y','Y',
            SYSTIMESTAMP, 'SYSTEM'
        );
    END;
BEGIN
    FOR m IN 1..16 LOOP
        grant_all(1, m); -- Super Admin
    END LOOP;
    -- Branch Manager: all except RBAC
    FOR m IN 1..15 LOOP
        INSERT INTO POS_PERMISSIONS
            (PID_PERMISSION, PID_GROUP, PID_MODULE,
             CAN_VIEW, CAN_CREATE, CAN_EDIT, CAN_DELETE,
             CAN_APPROVE, CAN_PRINT, CAN_EXPORT, CAN_FINALIZE, CAN_CANCEL,
             INSERTED_DATE, INSERTED_BY)
        VALUES (
            SEQ_POS_PERMISSIONS.NEXTVAL, 2, m,
            'Y','Y','Y','N','Y','Y','Y','Y','Y',
            SYSTIMESTAMP, 'SYSTEM'
        );
    END LOOP;
    -- Pharmacist: Sales + POS + Inventory
    FOR m IN (SELECT pid_module FROM ACL_MODULE_INFO WHERE ROUTE_KEY IN ('sales','quicksales','activity','inventory','reports','dashboard','salesdiscount')) LOOP
        INSERT INTO POS_PERMISSIONS
            (PID_PERMISSION, PID_GROUP, PID_MODULE,
             CAN_VIEW, CAN_CREATE, CAN_EDIT, CAN_DELETE,
             CAN_APPROVE, CAN_PRINT, CAN_EXPORT, CAN_FINALIZE, CAN_CANCEL,
             INSERTED_DATE, INSERTED_BY)
        VALUES (
            SEQ_POS_PERMISSIONS.NEXTVAL, 3, m.pid_module,
            'Y','Y','Y','N','N','Y','Y','Y','N',
            SYSTIMESTAMP, 'SYSTEM'
        );
    END LOOP;
END;
