/* ─────────────────────────────────────────────────────────────────────────────
   Sales targets.

   The Sales Performance screen showed eight salespeople, their monthly targets,
   their actuals, their commission and six months of trend — all of it generated
   in the browser by a seeded random number generator in mockData.js:

       target: int(rng, 400000, 900000),
       actual: round2(target * (0.7 + rng() * 0.5)),
       commission: 0.025,

   None of those people work here and none of those figures describe this
   business. The page had no backend at all.

   ── What the data can and cannot support ──

   Actuals are measurable. Every invoice records INSERTED_BY, the username that
   raised it, so sales per person is a real, auditable figure.

   POS_TRANSACTION_MST.PID_EMPLOYEE looks like the natural attribution and is
   not: it is NULL on all 140,390 sales in this database. Nothing has ever
   written it, so it cannot be the basis of a report.

   Targets are not measurable — they are a management decision, and nothing
   recorded one. This table is where they live now, so the screen can show
   achievement against a number somebody chose rather than one a generator
   invented. A person with no target set is reported on actuals alone rather
   than being given a fabricated one.

   ── Shape ──

   One row per person per month per branch. Monthly because that is the period
   targets are set and reviewed in, and because a target with no period is not a
   target. Commission travels on the same row: it is agreed with the target, and
   it changes when the target changes.

   PID_USER rather than the username, so renaming a login does not orphan the
   history. The actuals join back through ACL_USER.USER_NAME, which is unique.

   Identity rather than a sequence, deliberately. V18, V38, V39, V48 and V52 were
   each written to repair a sequence left behind its table by a hand-picked id.
   An identity column cannot drift.
   ───────────────────────────────────────────────────────────────────────────── */

CREATE TABLE IF NOT EXISTS pharma.pos_sales_target (
    pid_target      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pid_org         bigint         NOT NULL,
    pid_branch      bigint         NOT NULL,
    pid_user        bigint         NOT NULL,
    /* First day of the month the target applies to. A date rather than a
       year/month pair so ordinary date comparison works in every query. */
    period_month    date           NOT NULL,
    target_amount   numeric(14,2)  NOT NULL DEFAULT 0,
    /* Percent, not a fraction: 2.5 means 2.5%. Stored the way it is written on
       screen and in the agreement, so nobody has to remember which it is. */
    commission_pct  numeric(6,3)   NOT NULL DEFAULT 0,
    status          varchar(1)     DEFAULT 'Y',
    inserted_by     varchar(50),
    inserted_date   timestamp(6)   DEFAULT CURRENT_TIMESTAMP,
    updated_by      varchar(50),
    updated_date    timestamp(6),

    CONSTRAINT fk_sales_target_user   FOREIGN KEY (pid_user)   REFERENCES pharma.acl_user(pid_user),
    CONSTRAINT fk_sales_target_branch FOREIGN KEY (pid_branch) REFERENCES pharma.all_branch(pid_branch),

    /* One target per person per month per branch. Without this a second save
       creates a second row and the screen silently sums two targets. */
    CONSTRAINT uq_sales_target UNIQUE (pid_branch, pid_user, period_month),

    /* A negative target is meaningless, and a commission above 100% of revenue
       is a data-entry slip that would otherwise be paid out. */
    CONSTRAINT ck_sales_target_amount     CHECK (target_amount >= 0),
    CONSTRAINT ck_sales_target_commission CHECK (commission_pct >= 0 AND commission_pct <= 100),
    /* Targets are monthly, so the period is always the first of a month.
       Enforced rather than trusted: a target stored mid-month would never match
       the period the screen asks for and would look like a save that vanished. */
    CONSTRAINT ck_sales_target_period     CHECK (period_month = date_trunc('month', period_month)::date)
);

/* The screen reads one branch and one month at a time. */
CREATE INDEX IF NOT EXISTS ix_sales_target_period
    ON pharma.pos_sales_target (pid_branch, period_month);

COMMENT ON TABLE pharma.pos_sales_target IS
  'Monthly sales target and commission rate per person per branch. Actuals are '
  'not stored here — they are counted from POS_TRANSACTION_MST.INSERTED_BY.';

/* Nothing is seeded. A target is a decision somebody has to make, and inventing
   opening figures is what this table exists to stop. */

SELECT count(*) AS targets_now FROM pharma.pos_sales_target;
